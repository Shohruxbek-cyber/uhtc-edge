"""External review (9 Nov 2026): calculations that need no new simulation.

  R4 (A5) rarefaction  free-stream Knudsen number Kn_inf = lambda_inf / R_n (1976 Standard Atmosphere, hard-sphere mean
                       free path lambda = (mu / rho) sqrt(pi / (2 R T))) and the value at the edge of the stagnation-point
                       boundary layer, Kn_e = lambda_e / R_n (equilibrium edge state of the model: T_e, rho_e, mu_e, gas
                       constant of the mixture p_s / (rho_e T_e)), for R_n = 1, 3, 10 mm at 20, 30, 40 km and the highest
                       passing 2D Mach number of each column (fully catalytic); with the heating ratio q_rare/q_cont of
                       Kolodziej (1997) Eq. 7, the relation runs/final_review/analyses.py already uses (Re_t2 < 1e5).
  R6 (A11) dynamic pressure  q_inf = rho_inf V^2 / 2 at the highest passing 2D Mach number of the 15 band columns, along
                       the X-43A path of Q1 above Mach 8, and at
                       Mach 12 (top of the map) at 20 and 40 km.
Writes runs/final_review/external_calcs.json and external_calcs.md.
Run: python runs/final_review/external_calcs.py
"""
import csv
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "runs"))
from uhtc import atmosphere as atm  # noqa: E402
import common  # noqa: E402

OUT = Path(__file__).resolve().parent
A_KOL = [-1.38151, 2.26375, -0.54005, -0.02164, 0.02016, -0.00170]  # Kolodziej 1997 Eq. 7 (as analyses.py)
R_AIR = 287.05


def lam(mu, rho, R_gas, T):
    return mu / rho * math.sqrt(math.pi / (2.0 * R_gas * T))


def main():
    bnd = [r for r in csv.DictReader(open(ROOT / "runs" / "analysis" / "boundaries_2d.csv", encoding="utf-8"))
           if r["catalysis"] == "fc"]
    Ms = {(float(r["R_n_mm"]), float(r["alt_km"])): float(r["M_s_2d"]) for r in bnd}
    kn = []
    for R_mm in (1.0, 3.0, 10.0):
        for z_km in (20.0, 30.0, 40.0):
            M = Ms[(R_mm, z_km)]
            R = R_mm * 1e-3
            s = common.stag_state(M, z_km * 1e3)
            T, p, rho = (float(v) for v in atm.state(z_km * 1e3))
            l_inf = lam(float(atm.viscosity(T)), rho, R_AIR, T)
            R_e = s.p_s / (s.rho_e * s.T_e)
            l_e = lam(s.mu_e, s.rho_e, R_e, s.T_e)
            Re = s.rho_e * R * math.sqrt(s.H_s) / s.mu_e
            X = math.log10(Re)
            q_ratio = sum(a * X ** i for i, a in enumerate(A_KOL)) if Re < 1e5 else 1.0
            kn.append(dict(R_mm=R_mm, z_km=z_km, M_s=M, lambda_inf_m=l_inf, Kn_inf=l_inf / R, lambda_e_m=l_e,
                           Kn_e=l_e / R, T_e=s.T_e, Re_t2=Re, q_rare_over_cont=q_ratio))
    qd = []
    for (R_mm, z_km), M in sorted(Ms.items()):
        if z_km not in (20.0, 25.0, 30.0, 35.0, 40.0):
            continue
        s = common.stag_state(M, z_km * 1e3)
        qd.append(dict(R_mm=R_mm, z_km=z_km, M=M, q_inf_kPa=0.5 * s.rho_inf * s.V ** 2 / 1e3))
    for z_km in (20.0, 40.0):
        T, p, rho = (float(v) for v in atm.state(z_km * 1e3))
        V = 12.0 * math.sqrt(1.4 * R_AIR * T)
        qd.append(dict(R_mm=None, z_km=z_km, M=12.0, q_inf_kPa=0.5 * rho * V ** 2 / 1e3))
    # X-43A flight path of Q1 (digitized Karlgaard et al. 2005), 1976 atmosphere, the part above Mach 8
    import numpy as np
    a = np.loadtxt(ROOT / "runs" / "trajectory" / "x43a_mach10.csv", delimiter=",")
    T, p, rho = atm.state(a[:, 1])
    q = 0.5 * rho * (a[:, 2] * np.sqrt(1.4 * R_AIR * T)) ** 2 / 1e3
    m = a[:, 2] > 8.0
    x43a = dict(q_min_kPa=float(q[m].min()), q_max_kPa=float(q[m].max()), z_min_km=float(a[m, 1].min() / 1e3),
                z_max_km=float(a[m, 1].max() / 1e3))
    res = dict(knudsen=kn, dynamic_pressure=qd, x43a_above_mach8=x43a)
    (OUT / "external_calcs.json").write_text(json.dumps(res, indent=1, default=float), encoding="utf-8")
    lines = ["# External review: Knudsen numbers (R4) and dynamic pressure (R6)", "",
             "Generated by `runs/final_review/external_calcs.py`. Highest passing 2D Mach number, fully catalytic.", "",
             "| R_n (mm) | z (km) | Mach | lambda_inf (um) | Kn_inf | lambda_e (um) | Kn_e | Re_t2 | q_rare/q_cont |",
             "|---|---|---|---|---|---|---|---|---|"]
    for k in kn:
        lines.append(f"| {k['R_mm']:g} | {k['z_km']:g} | {k['M_s']:g} | {k['lambda_inf_m'] * 1e6:.3g} | "
                     f"{k['Kn_inf']:.3g} | {k['lambda_e_m'] * 1e6:.3g} | {k['Kn_e']:.3g} | {k['Re_t2']:.0f} | "
                     f"{k['q_rare_over_cont']:.3f} |")
    lines += ["", "| R_n (mm) | z (km) | Mach | q_inf (kPa) |", "|---|---|---|---|"]
    for q in qd:
        lines.append(f"| {q['R_mm'] if q['R_mm'] is not None else '-'} | {q['z_km']:g} | {q['M']:g} | "
                     f"{q['q_inf_kPa']:.1f} |")
    lines += ["", f"X-43A path above Mach 8 ({x43a['z_min_km']:.1f}-{x43a['z_max_km']:.1f} km): q_inf "
                  f"{x43a['q_min_kPa']:.1f}-{x43a['q_max_kPa']:.1f} kPa"]
    (OUT / "external_calcs.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
