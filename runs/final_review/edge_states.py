"""Final review (8 Nov 2026, R2-01): equilibrium edge states of the ground tests beyond the 6000 K end of the JANAF tables.

  backtest   tables cut at 5000 K and extended to 6000 K (thermo.extended_tables) against the full tables: enthalpy,
             dissociation enthalpy h_D and the non-catalytic factor of equilibrium air at 6000 K
  saha       ionised fraction of N and O atoms in neutral equilibrium air at 7000-9000 K (single ionisation, ground-state
             degeneracy ratios 9/4 for N and 4/9 for O), and the enthalpy it would bind, at the V8 pressures
  edges      edge temperature and h_D of every V8 and V9 step with the extended tables (coupled.PrescribedConditions),
             against the state clipped at 5998 K that was used before
Writes runs/final_review/edge_states.json and edge_states.md.
"""
import copy
import json
import sys
from pathlib import Path

import numpy as np
from scipy.optimize import brentq

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
from uhtc import coupled as cp, heating as ht, thermo as th  # noqa: E402

OUT = Path(__file__).resolve().parent
k_B, h_P, m_e, eV, N_A = 1.380649e-23, 6.62607015e-34, 9.1093837e-31, 1.602176634e-19, 6.02214076e23


def backtest():
    full = {sp: th.table(sp) for sp in ("N2", "O2", "N", "O", "NO")}
    cuts = {}
    for sp, t in full.items():
        c, k = copy.copy(t), t.T <= 5000.0
        c.T, c.Cp, c.S, c.dH, c.dfH, c.dfG = t.T[k], t.Cp[k], t.S[k], t.dH[k], t.dfH[k], t.dfG[k]
        cuts[sp] = c
    table = th.table
    out = {}
    try:
        for p in (0.042 * 101325.0, 18e3):
            th.table = lambda sp: full[sp]
            _, h0, hD0 = th.mixture_props(th.equilibrium_air(6000.0, p), 6000.0)
            th.table = lambda sp: cuts[sp]
            with th.extended_tables(9000.0):
                _, h1, hD1 = th.mixture_props(th.equilibrium_air(6000.0, p), 6000.0)
            out[f"{p / 1e3:.2f} kPa"] = dict(h_rel=h1 / h0 - 1, hD_rel=hD1 / hD0 - 1,
                                             f_nc_diff=float(ht.noncatalytic_factor(h1, hD1) - ht.noncatalytic_factor(h0, hD0)))
    finally:
        th.table = table
    return out


def saha():
    out = {}
    with th.extended_tables(9000.0):
        for p in (0.042 * 101325.0, 0.058 * 101325.0, 18e3):
            for T in (7000.0, 8000.0, 8999.0):
                x = th.equilibrium_air(T, p)
                M, h, hD = th.mixture_props(x, T)
                lam3 = (2 * np.pi * m_e * k_B * T / h_P ** 2) ** 1.5
                n = p / (k_B * T)
                S = {sp: (IP, 2 * g * lam3 * np.exp(-IP * eV / (k_B * T)) / n) for sp, IP, g in
                     (("N", 14.534, 9 / 4), ("O", 13.618, 4 / 9))}
                f = lambda xe: sum(x[sp] * s / (xe + s) for sp, (IP, s) in S.items()) - xe
                xe = brentq(f, 1e-15, 1.0)
                e_ion = sum(x[sp] * s / (xe + s) * IP for sp, (IP, s) in S.items()) * eV * N_A / M  # J/kg
                atoms = x["N"] + x["O"]
                out[f"{p / 1e3:.2f} kPa, {T:.0f} K"] = dict(h_MJkg=h / 1e6, hD_MJkg=hD / 1e6, x_N2=x["N2"],
                                                           ionised_atom_fraction=xe / atoms, h_ion_over_hD=e_ion / hD)
    return out


def edges():
    steps = {"V8-1 15 MJ/kg": (15e6, 0.042 * 101325.0), "V8-1 30 MJ/kg": (30e6, 0.042 * 101325.0),
             "V8-1 45 MJ/kg": (45e6, 0.042 * 101325.0), "V8-1 active 15 MJ/kg": (15e6, 0.058 * 101325.0),
             "V8-1 active 30 MJ/kg": (30e6, 0.058 * 101325.0), "V8-1 active 45 MJ/kg": (45e6, 0.058 * 101325.0),
             "V8-2 condition 1": (27.9e6, 18e3), "V8-2 condition 2": (20.8e6, 18e3),
             "V9 low stage": (12.0e6, 1.0e4 + 30.0), "V9 1.8 high": (17.7e6, 1.0e4 + 60.0),
             "V9 1.5 high": (18.6e6, 1.0e4 + 75.0), "V9 1.6 high": (21.7e6, 1.0e4 + 90.0)}
    out = {}
    for name, (H, p) in steps.items():
        c = cp.PrescribedConditions([(0.0, H, p)], R_n=0.01)
        Te_old = th.T_air_equilibrium(min(H, th.h_air_equilibrium(5998.0, p)), p)
        _, _, hD_old = th.mixture_props(th.equilibrium_air(Te_old, p), Te_old)
        out[name] = dict(T_e=c.edge_T[0], held_at_T_max=c.edge_held[0], h_D_MJkg=c.flows[0].h_D / 1e6, f_nc=c.flows[0].f_nc,
                         T_e_clipped=float(Te_old), h_D_clipped_MJkg=hD_old / 1e6,
                         f_nc_clipped=float(ht.noncatalytic_factor(H, hD_old)))
    return out


def main():
    res = dict(backtest=backtest(), saha=saha(), edges=edges())
    (OUT / "edge_states.json").write_text(json.dumps(res, indent=1), encoding="utf-8")
    lines = ["# Final review: ground-test edge states beyond 6000 K (generated by runs/final_review/edge_states.py)", ""]
    for sec, d in res.items():
        lines += [f"## {sec}", ""]
        for k, v in d.items():
            lines.append(f"- {k}: " + ", ".join(f"{a} = {b:.4g}" if isinstance(b, float) else f"{a} = {b}" for a, b in v.items()))
        lines.append("")
    (OUT / "edge_states.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
