"""External review (9 Nov 2026): 1D base cases B1 and B2 with the variants of runs R2 (A6) and R5 (A9).

  kd_arrh      depletion rate k_d(T) from the Arrhenius fit of runs/final_review/kd_arrhenius.py, extrapolated above
               2073 K
  kd_arrh_cap  the same law held at its 2073 K value above 2073 K
  gate_0.5     criterion (a) armed after 0.5 um of converted composite instead of 1 um
  gate_2       the same after 2 um
  gate_1nm     the same after 1 nm
  gate_0       no gate: criterion (a) armed from the start, before any glass has formed
Base cases as in runs/sensitivity/base_cases.json (f_SiC 0.2, stop at the first failure, 1800 s cap).
Writes runs/final_review/external_1d.json and external_1d.md.
Run: python runs/final_review/external_1d.py
"""
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "runs"))
import common  # noqa: E402

OUT = Path(__file__).resolve().parent
BASE = json.loads((ROOT / "runs" / "sensitivity" / "base_cases.json").read_text(encoding="utf-8"))
KD = json.loads((OUT / "kd_arrhenius.json").read_text(encoding="utf-8"))["oxparams"]
VARIANTS = {
    "base": {},
    "kd_arrh": dict(kd_E=KD["kd_E"], kd_mult=KD["kd_mult"]),
    "kd_arrh_cap": dict(kd_E=KD["kd_E"], kd_mult=KD["kd_mult"], kd_T_max=KD["kd_T_ref"]),
    "gate_0.5": dict(x_ox_min=0.5e-6),
    "gate_2": dict(x_ox_min=2e-6),
    "gate_1nm": dict(x_ox_min=1e-9),
    "gate_0": dict(x_ox_min=0.0),
}


def case(b, ox):
    c = BASE[b]
    return dict(mach=c["mach"], alt=c["alt"], R_n=c["R_n"], catalysis=c["catalysis"], f_SiC=0.2, stop="first",
                id=b, ox=dict(ox))


def main():
    res = {}
    for b in ("B1", "B2"):
        for name, ox in VARIANTS.items():
            r = common.run_case(case(b, ox))
            res[f"{b}_{name}"] = {k: r[k] for k in ("t_fail", "mode", "t_glass", "t_active", "t_limit", "T_s_max",
                                                    "dep_um_end", "glass_um_end", "error") if k in r}
        base = res[f"{b}_base"]["t_fail"]
        for name in VARIANTS:
            t = res[f"{b}_{name}"]["t_fail"]
            res[f"{b}_{name}"]["factor_vs_base"] = (t / base) if (t == t and base == base) else math.nan
    (OUT / "external_1d.json").write_text(json.dumps(res, indent=1, default=float), encoding="utf-8")
    lines = ["# External review: 1D base cases with the depletion-rate and gate variants", "",
             "Generated by `runs/final_review/external_1d.py`.", "",
             "| case | variant | t_fail (s) | mode | factor vs base | T_s,max (K) | depleted layer at end (um) |",
             "|---|---|---|---|---|---|---|"]
    for k, v in res.items():
        b, name = k.split("_", 1)
        lines.append(f"| {b} | {name} | {v['t_fail']:.1f} | {v['mode']} | {v['factor_vs_base']:.3f} | "
                     f"{v['T_s_max']:.1f} | {v['dep_um_end']:.1f} |")
    (OUT / "external_1d.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
