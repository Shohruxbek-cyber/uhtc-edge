"""Version 3, Task 1: the glass-flow numbers quoted in the paper, from the saved runs (no model runs here).

Inputs : runs/analysis/v3_boundaries.csv (15 band columns per variant, analyze_v3.py)
         runs/envelope_2d/flow_*.jsonl, flowgrid_R*.jsonl, flowrefine_R*.jsonl, transport_alpha_0.005.jsonl
         validation/V2b_flow_numerics/v2b_results.json, validation/V9b_glassflow/{v9b_results,beta_estimate}.json
Output : runs/analysis/flow_numbers.json and flow_numbers.md
Usage  : python runs/analysis/flow_numbers.py
"""
import csv
import glob
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
E2 = ROOT / "runs/envelope_2d"


def load(p):
    return [json.loads(l) for l in open(p, encoding="utf-8") if l.strip()]


def key(r):
    return (round(r["R_n"] * 1e3, 6), round(r["alt"] / 1e3, 6), r["mach"])


def main():
    out = {}
    # 1. film audit of every flow run
    files = sorted(glob.glob(str(E2 / "flow_*.jsonl")) + glob.glob(str(E2 / "flowgrid_R*.jsonl")) + glob.glob(str(E2 / "flowrefine_R*.jsonl")))
    aud = [r["flow_audit_max"] for f in files for r in load(f) if not r.get("error") and r.get("flow_audit_max") is not None]
    out["film_audit"] = dict(runs=len(aud), max=max(aud))
    # 2. band columns per flow variant: shift and change of the failure time at the reference's lowest failing Mach
    rows = [r for r in csv.DictReader(open(ROOT / "runs/analysis/v3_boundaries.csv", encoding="utf-8")) if r["stage"] == "flow"]
    var = {}
    for r in rows:
        v = var.setdefault(r["variant"], dict(shifts={}, dt_pct=[], mode_changes=0))
        v["shifts"][r["shift_steps"]] = v["shifts"].get(r["shift_steps"], 0) + 1
        v["mode_changes"] += r["mode_ref"] != r["mode"]
        tr, tv = r["t_fail_ref_at_old"], r["t_fail_at_old"]
        if tr not in ("", "None", "nan") and tv not in ("", "None", "nan") and r["mode_at_old"] == "glass" and r["mode_ref"] == "glass":
            v["dt_pct"].append(100 * (float(tv) / float(tr) - 1))
    for k, v in var.items():
        v["dt_pct_range"] = [min(v["dt_pct"], default=None), max(v["dt_pct"], default=None)]
        v["n_dt"] = len(v.pop("dt_pct"))
    out["band_variants"] = var
    # 3. alpha 0.005: flow on against flow off at the points run in both
    off = {key(r): r for r in load(E2 / "transport_alpha_0.005.jsonl") if not r.get("error")}
    on = {key(r): r for r in load(E2 / "flow_flow_alpha_0.005.jsonl") if not r.get("error")}
    shared = sorted(set(off) & set(on))
    dT = [on[k]["T_s_max"] - off[k]["T_s_max"] for k in shared]
    shifted = [r for r in csv.DictReader(open(ROOT / "runs/analysis/v3_boundaries.csv", encoding="utf-8"))
               if r["variant"] == "flow_alpha_0.005" and r["shift_steps"] not in ("0.0", "0", "")]
    pts = []
    for r in shifted:  # the new highest surviving point, which failed without flow
        k = (float(r["R_mm"]), float(r["alt_km"]), float(r["M_s"]))
        if k in off and k in on:
            pts.append(dict(R=k[0], alt=k[1], M=k[2], mode_off=off[k]["mode"], t_off=off[k]["t_fail"], mode_on=on[k]["mode"],
                            glass_off_um=off[k]["glass_um_end"], glass_on_um=on[k]["glass_um_end"],
                            Tmax_off=off[k]["T_s_max"], Tmax_on=on[k]["T_s_max"]))
    out["alpha_0.005"] = dict(shared_points=len(shared), dTmax_K_range=[min(dT), max(dT)], columns_shifted=len(shifted),
                              shifts=sorted({r["shift_steps"] for r in shifted}), shifted_points=pts,
                              glass_off_um_range=[min(p["glass_off_um"] for p in pts), max(p["glass_off_um"] for p in pts)] if pts else None,
                              glass_on_um_range=[min(p["glass_on_um"] for p in pts), max(p["glass_on_um"] for p in pts)] if pts else None,
                              dTmax_shifted_K=[min(p["Tmax_on"] - p["Tmax_off"] for p in pts), max(p["Tmax_on"] - p["Tmax_off"] for p in pts)] if pts else None)
    # 4. checks
    out["V2b"] = json.loads((ROOT / "validation/V2b_flow_numerics/v2b_results.json").read_text(encoding="utf-8"))
    v9b = json.loads((ROOT / "validation/V9b_glassflow/v9b_results.json").read_text(encoding="utf-8"))
    out["V9b_keys"] = list(v9b) if isinstance(v9b, dict) else None
    out["beta"] = json.loads((ROOT / "validation/V9b_glassflow/beta_estimate.json").read_text(encoding="utf-8"))
    (ROOT / "runs/analysis/flow_numbers.json").write_text(json.dumps(out, indent=1, default=str), encoding="utf-8")
    L = ["# Glass-flow numbers quoted in the paper", "", "Generated by `runs/analysis/flow_numbers.py`.", "",
         f"- Film audit: {out['film_audit']['runs']} flow runs, largest relative error {out['film_audit']['max']:.2e}.", ""]
    L += ["## Band columns per variant (glass-loss time at the reference's lowest failing Mach, glass in both)", ""]
    for k, v in var.items():
        rg = "none" if v["n_dt"] == 0 else f"{v['dt_pct_range'][0]:.1f} to {v['dt_pct_range'][1]:.1f} %"
        L.append(f"- {k}: shifts {v['shifts']}; first-failure changes {v['mode_changes']}; change of the glass-loss time "
                 f"{rg} over {v['n_dt']} columns")
    a = out["alpha_0.005"]
    L += ["", "## Evaporation coefficient 0.005, flow on against flow off", "",
          f"- {a['shared_points']} shared points; change of the peak surface temperature {a['dTmax_K_range'][0]:.1f} to {a['dTmax_K_range'][1]:.1f} K",
          f"- {a['columns_shifted']} columns shifted ({a['shifts']} steps); at their new highest surviving point the film at the end is "
          f"{a['glass_off_um_range']} um without flow and {a['glass_on_um_range']} um with flow; peak temperature change {a['dTmax_shifted_K']} K"]
    L += [f"  - {p}" for p in a["shifted_points"]]
    (ROOT / "runs/analysis/flow_numbers.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    print(json.dumps(out["V2b"], indent=1)[:1500])
    print(json.dumps(out["beta"], indent=1)[:1500])


if __name__ == "__main__":
    main()
