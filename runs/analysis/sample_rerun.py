"""Rerun a fixed random sample of stored cases and compare with the saved outputs.

The full set of runs takes about 20 hours, so reproducibility is shown on a sample drawn with a fixed seed from every family of
runs. Criterion, set before the first run: every case gives the same failure mode, and every stored failure time and peak
temperature agrees within 1e-6 relative.

The 2D grids predate the Eq. 8 data fix (CHANGELOG.md), so T_transition in those files is the old value and is not compared; that
fix cannot change a first failure in 2D. Output: runs/analysis/sample_rerun.md
"""
import json
import math
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "runs"))
import common  # noqa: E402

SEED = 20261104
TOL = 1e-6
FAMILIES_1D = [("runs/envelope/set_A.jsonl", 12), ("runs/envelope/set_B.jsonl", 6), ("runs/envelope/set_C.jsonl", 6), ("runs/envelope/set_D.jsonl", 6),
               ("runs/sensitivity/oat_B1.jsonl", 4), ("runs/sensitivity/oat_B2.jsonl", 4), ("runs/sensitivity/lhs_B1.jsonl", 4),
               ("runs/sensitivity/lhs_B2.jsonl", 4), ("runs/sensitivity/oat_extra.jsonl", 3), ("runs/sensitivity/oat_lewis.jsonl", 2)]
FAMILIES_2D = [("runs/envelope_2d/grid.jsonl", 10), ("runs/envelope_2d/refine.jsonl", 4), ("runs/envelope_2d/band_worst.jsonl", 2),
               ("runs/envelope_2d/kinetics_kp_x3.jsonl", 2), ("runs/envelope_2d/active_pa_balat.jsonl", 2), ("runs/envelope_2d/flank_flank_x2.jsonl", 3),
               ("runs/envelope_2d/flank_sharp_cone.jsonl", 2), ("runs/envelope_2d/oxidant_o_as_o2.jsonl", 3)]
INPUTS = ("mach", "alt", "R_n", "catalysis", "f_SiC", "k_mult", "cp_mult", "heat_mult", "mtf", "cylinder", "stop", "t_cap", "depth", "geometry",
          "heat_dist", "flank_mult", "theta_deg", "L_flank", "oxidant", "dt_max", "record_every")
COMPARE = ("t_glass", "t_limit", "t_fail", "T_s_max")


def to_case(row, tag):
    c = {k: row[k] for k in INPUTS if k in row}
    c["ox"] = {k[3:]: v for k, v in row.items() if k.startswith("ox_")}
    c["id"] = f"{tag}|{row['case_id']}"
    return c


def draw(families, rng):
    cases, stored = [], {}
    for rel, n in families:
        rows = [r for r in common.load(ROOT / rel) if not r.get("error")]
        tag = Path(rel).stem
        for r in rng.sample(rows, min(n, len(rows))):
            c = to_case(r, tag)
            cases.append(c)
            stored[c["id"]] = r
    return cases, stored


def same(a, b):
    if a is None or b is None:
        return a is b
    if isinstance(a, float) and (math.isnan(a) or math.isnan(b)):
        return math.isnan(a) and math.isnan(b)
    return abs(a - b) <= TOL * max(1.0, abs(a))


def main():
    rng = random.Random(SEED)
    c1, s1 = draw(FAMILIES_1D, rng)
    c2, s2 = draw(FAMILIES_2D, rng)
    out1, out2 = ROOT / "runs/analysis/_sample_1d.jsonl", ROOT / "runs/analysis/_sample_2d.jsonl"
    for f in (out1, out2):
        f.unlink(missing_ok=True)
    common.run_all(c1, out1)
    common.run_all(c2, out2, runner=common.run_case_2d)
    stored = {**s1, **s2}
    fam, bad, worst = {}, [], 0.0
    for r in common.load(out1) + common.load(out2):
        cid = r["case_id"]
        s = stored[cid]
        tag = cid.split("|")[0]
        ok = r["mode"] == s["mode"] and not r.get("error")
        for k in COMPARE:
            a, b = s.get(k), r.get(k)
            if a is None or b is None:
                continue
            ok = ok and same(a, b)
            if a == a and b == b:
                worst = max(worst, abs(a - b) / max(1.0, abs(a)))
        fam.setdefault(tag, [0, 0])
        fam[tag][0] += 1
        fam[tag][1] += 1 if ok else 0
        if not ok:
            bad.append((cid, s["mode"], s.get("t_fail"), r["mode"], r.get("t_fail")))
    total, good = sum(v[0] for v in fam.values()), sum(v[1] for v in fam.values())
    L = ["# Sample rerun against the saved outputs", "", f"Generated by `runs/analysis/sample_rerun.py`, seed {SEED}. Criterion set before the run: same failure mode, and "
         f"{', '.join(COMPARE)} within {TOL:g} relative.", "", "| Family | Cases | Agree |", "|---|---|---|"]
    L += [f"| {k} | {v[0]} | {v[1]} |" for k, v in fam.items()]
    L += ["", f"{good} of {total} cases agree; largest relative difference {worst:.2e}."]
    if bad:
        L += ["", "Disagreements (case, stored mode, time, rerun mode, time):", ""] + [f"- {b}" for b in bad]
    (ROOT / "runs/analysis/sample_rerun.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    for f in (out1, out2):
        f.unlink(missing_ok=True)
        f.with_suffix(".csv").unlink(missing_ok=True)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
