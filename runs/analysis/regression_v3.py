"""Bit-exact regression of the saved-case sample with the version-3 modules switched off (author's rule 0.5).

The 79 cases are those of runs/analysis/sample_rerun.py (same seed, same families: 51 x 1D, 28 x 2D). Every output field that the
stored row and the rerun row both hold is compared for exact equality (two NaN count as equal). Not compared: the inputs, cpu_s,
and, for the 2D grids, T_transition, which predates the Eq. 8 data fix (sample_rerun.py explains why). Criterion, fixed before the
first module was written: every compared field identical, no error, same failure mode.

Usage: python runs/analysis/regression_v3.py [--glass-flow on|off] [--thermoelastic on|off] [--flank-model baseline|sharpcone|integral]
With every module off (the default) the run must be bit-exact. With a module on, the report lists which fields changed (rule 0.5c).
Output: runs/analysis/regression_v3.md (all off) or runs/analysis/regression_v3_<flags>.md.
"""
import argparse
import math
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "runs"))
sys.path.insert(0, str(ROOT / "runs" / "analysis"))
import common  # noqa: E402
import sample_rerun as sr  # noqa: E402

SKIP = {"cpu_s", "case_id"} | set(sr.INPUTS)


def equal(a, b):
    if isinstance(a, float) and isinstance(b, float) and math.isnan(a) and math.isnan(b):
        return True
    return a == b


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--glass-flow", choices=("on", "off"), default="off")
    ap.add_argument("--thermoelastic", choices=("on", "off"), default="off")
    ap.add_argument("--flank-model", choices=("baseline", "sharpcone", "integral"), default="baseline")
    a = ap.parse_args()
    flags = dict(glass_flow=a.glass_flow, thermoelastic=a.thermoelastic, flank_model=a.flank_model)
    off = flags == dict(glass_flow="off", thermoelastic="off", flank_model="baseline")
    rng = random.Random(sr.SEED)
    c1, s1 = sr.draw(sr.FAMILIES_1D, rng)
    c2, s2 = sr.draw(sr.FAMILIES_2D, rng)
    if not off:  # module switches travel with the case; with all off the case dicts are those of sample_rerun.py
        for c in c1 + c2:
            c.update({k: v for k, v in flags.items() if v not in ("off", "baseline")})
    tag = "" if off else "_" + "_".join(f"{k}-{v}" for k, v in flags.items() if v not in ("off", "baseline"))
    out1, out2 = ROOT / f"runs/analysis/_reg{tag}_1d.jsonl", ROOT / f"runs/analysis/_reg{tag}_2d.jsonl"
    for f in (out1, out2):
        f.unlink(missing_ok=True)
    common.run_all(c1, out1)
    common.run_all(c2, out2, runner=common.run_case_2d)
    stored = {**s1, **s2}
    n, bad, changed = 0, [], {}
    for r in common.load(out1) + common.load(out2):
        s = stored[r["case_id"]]
        is2d = r["case_id"].split("|")[0] in {Path(p).stem for p, _ in sr.FAMILIES_2D}
        diffs = [k for k in s if k in r and k not in SKIP and not (is2d and k == "T_transition") and not equal(s[k], r[k])]
        if r.get("error"):
            diffs.append("error: " + r["error"])
        n += 1
        for k in diffs:
            changed.setdefault(k, []).append(r["case_id"])
        if diffs:
            bad.append((r["case_id"], diffs))
    L = ["# Regression of the saved-case sample, version-3 modules " + ("off (bit-exact rule 0.5b)" if off else "on (rule 0.5c)"), "",
         f"Generated by `runs/analysis/regression_v3.py`; flags {flags}; {n} cases (seed {sr.SEED}, families of sample_rerun.py). "
         "Every stored output field compared for exact equality.", ""]
    if not bad:
        L.append(f"**{n} of {n} cases identical in every compared field.**")
    else:
        L.append(f"{n - len(bad)} of {n} cases identical; {len(bad)} differ.")
        L += ["", "| Field | Cases that changed |", "|---|---|"] + [f"| {k} | {len(v)} |" for k, v in sorted(changed.items())]
        L += ["", "Cases:", ""] + [f"- {cid}: {', '.join(d)}" for cid, d in bad]
    md = ROOT / f"runs/analysis/regression_v3{tag}.md"
    md.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L[:8]))
    for f in (out1, out2):
        f.unlink(missing_ok=True)
        f.with_suffix(".csv").unlink(missing_ok=True)
    return 1 if (off and bad) else 0


if __name__ == "__main__":
    sys.exit(main())
